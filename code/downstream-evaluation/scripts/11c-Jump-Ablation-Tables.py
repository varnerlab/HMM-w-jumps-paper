"""Generate identical arXiv/JFDS table bodies from frozen jump experiment CSVs."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RESULTS = ROOT / "code/downstream-evaluation/results/jump-ablation"
with (RESULTS / "summary.csv").open() as stream:
    summary = {(r["window"], r["scenario"], r["method"]): r for r in csv.DictReader(stream)}
with (RESULTS / "paired-contrasts.csv").open() as stream:
    contrasts = {(r["window"], r["changed"], r["metric"]): r for r in csv.DictReader(stream)
                 if r["kind"] == "jump_setting"}

cases = [("off", "Off"), ("market_only", "Market only"),
         ("market_and_assets", "Market + assets")]
windows = [("training", r"Training: $2014$--$2024$, $423$ assets, $2{,}766$ days"),
           ("holdout_2025", r"Holdout: $2025$, $416$ assets, $249$ days")]
main = [r"% Generated by 11c-Jump-Ablation-Tables.py; do not edit numbers manually.",
        r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
        r"Jump setting & Method & KS (\%) & AD (\%) & ACF$_{25}$ & ACF$_{60}$ & $V_{\gen}$ \\",
        r"\midrule"]
uncertainty = [main[0], r"\begin{tabular}{@{}lrr@{}}", r"\toprule",
               r"Jump setting & $\Delta$ACF$_{25}$ [95\% MC interval] & $\Delta$KS [95\% MC interval] \\",
               r"\midrule"]
for index, (window, label) in enumerate(windows):
    if index:
        main.append(r"\midrule")
        uncertainty.append(r"\midrule")
    main.append(r"\multicolumn{7}{@{}l}{\textit{" + label + r"}} \\[2pt]")
    uncertainty.append(r"\multicolumn{3}{@{}l}{\textit{" + label + r"}} \\[2pt]")
    for case, display in cases:
        for method in ("naive", "hybrid"):
            r = summary[window, case, method]
            numbers = [f"{100*float(r[s]):.2f}" for s in ("ks_pass", "ad_pass")]
            numbers += [f"{float(r[s]):.5f}" for s in
                        ("abs_acf_mae25", "abs_acf_mae60", "variance_ratio_generator")]
            main.append(" & ".join([display, "Naive" if method == "naive" else "Corrected", *numbers]) + r" \\")
        if case != "off":
            cells = []
            for metric, scale, digits in (("abs_acf_mae25", 1, 5), ("ks_pass", 100, 2)):
                r = contrasts[window, case + "/hybrid", metric]
                values = [scale*float(r[s]) for s in ("mean_difference", "mc_low", "mc_high")]
                cells.append(f"${values[0]:.{digits}f}$ [${values[1]:.{digits}f}, {values[2]:.{digits}f}$]")
            uncertainty.append(" & ".join([display, *cells]) + r" \\")
main += [r"\bottomrule", r"\end{tabular}", ""]
uncertainty += [r"\bottomrule", r"\end{tabular}", ""]

# Episode incidence and breadth of the temporal change (anchors for the prose
# shares quoted in the uncertainty section and in Results).
with (RESULTS / "market-metrics.csv").open() as stream:
    market = [r for r in csv.DictReader(stream) if r["enabled"] == "true"]
with (RESULTS / "generator-metrics.csv").open() as stream:
    generators = [r for r in csv.DictReader(stream) if r["enabled"] == "true"]
with (RESULTS / "improvement-breadth.csv").open() as stream:
    breadth = {(r["window"], r["scenario"], r["method"]): r for r in csv.DictReader(stream)}
episodes = [main[0], r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
            r"Window & SPY paths with an episode & Asset paths with an episode (\%) "
            r"& Assets with lower ACF$_{25}$ error, market only (\%) & \ldots, market + assets (\%) \\",
            r"\midrule"]
for window, label in (("training", "Training"), ("holdout_2025", "Holdout")):
    rows = [r for r in market if r["window"] == window]
    n_active = sum(r["jump_active"] == "true" for r in rows)
    gens = [float(r["jump_active_rate"]) for r in generators if r["window"] == window]
    asset_share = 100 * sum(gens) / len(gens)
    improved = [100 * float(breadth[window, case, "hybrid"]["acf25_improved_fraction"])
                for case in ("market_only", "market_and_assets")]
    episodes.append(" & ".join([label, f"{n_active} of {len(rows):,}".replace(",", "{,}"),
                                f"{asset_share:.2f}", f"{improved[0]:.1f}", f"{improved[1]:.1f}"]) + r" \\")
episodes += [r"\bottomrule", r"\end{tabular}", ""]

# Manuscript content is updated in the preprint tree first, then in JFDS.
for tree in ("arxiv-paper", "jfds-paper"):
    target = ROOT / tree / "sections/tables"
    (target / "table7_jump_ablation.tex").write_text("\n".join(main))
    (target / "tableS_jump_ablation_uncertainty.tex").write_text("\n".join(uncertainty))
    (target / "tableS_jump_ablation_episodes.tex").write_text("\n".join(episodes))
    print(f"Wrote jump experiment tables to {target}")
